/* Мы не подключаем <stdio.h>, поэтому нам нужно 
   реализовать вывод через системный вызов write */

void _start() {
    const char msg[] = "Hello from bare C!\n";
    
    /* Системный вызов write(1, msg, 19) */
    /* 1 — это дескриптор stdout */
    __asm__(
        "mov $1, %%rax;"    // Номер системного вызова (sys_write)
        "mov $1, %%rdi;"    // Аргумент 1: куда писать (stdout)
        "mov %0, %%rsi;"    // Аргумент 2: адрес строки
        "mov $19, %%rdx;"   // Аргумент 3: длина строки
        "syscall;"
        :
        : "r"(msg)
        : "%rax", "%rdi", "%rsi", "%rdx"
    );

    /* Системный вызов exit(0) */
    /* Если не вызвать exit, программа упадет (Segmentation fault),
       так как ей некуда возвращаться после завершения _start */
    __asm__(
        "mov $60, %%rax;"   // Номер системного вызова (sys_exit)
        "xor %%rdi, %%rdi;" // Аргумент 1: код возврата (0)
        "syscall;"
        :
        :
        : "%rax", "%rdi"
    );
}
